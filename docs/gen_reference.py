"""Generate the reference pages from the code, so they cannot drift.

    uv run python docs/gen_reference.py          # rewrite docs/reference/*.md
    uv run python docs/gen_reference.py --check  # exit 1 if they are out of date

tests/test_docs.py runs the check, so CI fails when a model, command or
endpoint changes without regenerating.
"""

import inspect
import json
import sys
import tempfile
import types
import typing
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

import typer.main
from markdown.extensions.toc import slugify
from pydantic import BaseModel
from pydantic.fields import FieldInfo

REFERENCE = Path(__file__).parent / "reference"
HEADER = "<!-- Generated by docs/gen_reference.py; do not edit by hand. -->\n\n"


# ---------------------------------------------------------------- models


def _type(annotation: Any) -> str:
    origin, args = get_origin(annotation), get_args(annotation)
    if annotation is Any:
        return "any"
    if origin is Literal:
        return " \\| ".join(f"`{a}`" for a in args)
    if origin in (Union, types.UnionType):
        parts = [_type(a) for a in args if a is not type(None)]
        return " \\| ".join(parts) + (" \\| null" if type(None) in args else "")
    if origin in (list, typing.List):  # noqa: UP006
        return f"list of {_type(args[0])}" if args else "list"
    if origin in (dict, typing.Dict):  # noqa: UP006
        return f"map of {_type(args[0])} to {_type(args[1])}" if args else "map"
    if origin is typing.Annotated:
        return _type(args[0])
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return "object"
    if isinstance(annotation, type):
        return {"str": "string", "int": "integer", "float": "number", "bool": "boolean"}.get(
            annotation.__name__, annotation.__name__
        )
    return str(annotation).replace("typing.", "")


def _default(field: FieldInfo) -> str:
    if field.is_required():
        return "**required**"
    value = field.default_factory() if field.default_factory else field.default
    if isinstance(value, BaseModel):
        return "see below"
    if value is None:
        return "—"
    return f"`{json.dumps(value)}`"


def _models_in(annotation: Any) -> list[tuple[str, type[BaseModel]]]:
    """Nested models in an annotation, with the YAML path suffix that reaches them."""
    origin, args = get_origin(annotation), get_args(annotation)
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [("", annotation)]
    if origin in (list,):
        return [("[]" + s, m) for s, m in _models_in(args[0])] if args else []
    if origin in (dict,):
        return [(".<name>" + s, m) for s, m in _models_in(args[1])] if args else []
    if origin in (Union, types.UnionType, typing.Annotated):
        return [x for a in args for x in _models_in(a)]
    return []


def _doc(model: type[BaseModel]) -> str:
    doc = inspect.getdoc(model) or ""
    return "" if doc.startswith(("Usage docs", "!!! abstract")) else doc.split("\n\n")[0]


def model_sections(model: type[BaseModel], path: str, level: int = 2) -> str:
    """A table per model, depth-first, so nested sections follow their parent."""
    out: list[str] = []
    seen: set[tuple[str, type]] = set()

    def section(current_path: str, current: type[BaseModel]) -> None:
        if (current_path, current) in seen:
            return
        seen.add((current_path, current))
        out.append(f"{'#' * level} `{current_path}`\n")
        if doc := _doc(current):
            out.append(doc.replace("\n", " ") + "\n")
        if current.model_config.get("extra") == "allow":
            out.append("Other keys are passed to the connector (see *Connector options*).\n")
        out.append("| Key | Type | Default | Description |\n|---|---|---|---|")
        children: list[tuple[str, type[BaseModel]]] = []
        for name, field in current.model_fields.items():
            if field.exclude:
                continue
            description = (field.description or "").replace("|", "\\|").replace("\n", " ")
            kind = _type(field.annotation)
            for suffix, nested in _models_in(field.annotation):
                nested_path = f"{current_path}.{name}{suffix}".lstrip(".")
                children.append((nested_path, nested))
                kind = kind.replace("object", f"[object](#{slugify(nested_path, '-')})", 1)
            out.append(f"| `{name}` | {kind} | {_default(field)} | {description} |")
        out.append("")
        for child_path, child in children:
            section(child_path, child)

    section(path, model)
    return "\n".join(out)


def project_config() -> str:
    from ragkit.core.config import ProjectConfig
    from ragkit.ingest.connectors.confluence import ConfluenceOptions
    from ragkit.ingest.connectors.files import FilesOptions
    from ragkit.ingest.connectors.github import GitHubOptions
    from ragkit.ingest.connectors.notion import NotionOptions
    from ragkit.ingest.connectors.web import WebOptions

    connectors = [
        ("files", FilesOptions),
        ("web", WebOptions),
        ("github", GitHubOptions),
        ("confluence", ConfluenceOptions),
        ("notion", NotionOptions),
    ]
    parts = [
        HEADER,
        "# ragkit.yaml reference\n",
        "Every key of the project file, generated from `ragkit.core.config`. Strings may "
        "reference environment variables as `${VAR}` or `${VAR:-default}`; the project's "
        "`.env` is loaded first. Unknown keys are rejected, except under a source.\n",
        model_sections(ProjectConfig, "", level=2).replace("## ``", "## Top level", 1),
        "## Connector options\n",
        "Keys accepted under `collections.<name>.sources[]` for each built-in `type`.\n",
    ]
    for name, model in connectors:
        parts.append(model_sections(model, f"type: {name}", level=3))
    return "\n".join(parts)


def agent_manifest() -> str:
    from ragkit.agents.guardrails import DenyGuardrail, InjectionGuardrail, PiiGuardrail
    from ragkit.agents.manifest import AgentManifest

    parts = [
        HEADER,
        "# agent.yaml reference\n",
        "Every key of an agent's manifest, generated from `ragkit.agents.manifest`. "
        "Paths such as `system_prompt` and `output_schema` are relative to the agent's "
        "folder. Unknown keys are rejected.\n",
        model_sections(AgentManifest, "", level=2).replace("## ``", "## Top level", 1),
        "## Guardrails\n",
        "Entries of `guardrails`. `pii` and `prompt_injection` may also be written as "
        "plain strings to use their defaults.\n",
    ]
    for model in (PiiGuardrail, InjectionGuardrail, DenyGuardrail):
        kind = model.model_fields["type"].annotation.__args__[0]
        parts.append(model_sections(model, f"type: {kind}", level=3))
    return "\n".join(parts)


# ---------------------------------------------------------------- CLI


def cli() -> str:
    from ragkit.cli.main import app

    root = typer.main.get_command(app)
    parts = [
        HEADER,
        "# CLI reference\n",
        "`ragkit` commands, generated from `ragkit.cli`. Run any command with `--help` "
        "for the same information. Commands that read a project look for `ragkit.yaml` "
        "in the current directory or its parents.\n",
    ]

    # Typer bundles its own Click, so check by shape rather than by class.
    def walk(command: Any, words: list[str]) -> None:
        if hasattr(command, "commands"):
            for name in sorted(command.commands):
                sub = command.commands[name]
                if not sub.hidden:
                    walk(sub, [*words, name])
            return
        arguments = [p for p in command.params if p.param_type_name == "argument"]
        options = [p for p in command.params if p.param_type_name == "option" and p.name != "help"]
        usage = " ".join(
            ["ragkit", *words, "[OPTIONS]" if options else "", *(_arg_usage(a) for a in arguments)]
        )
        parts.append(f"## `ragkit {' '.join(words)}`\n")
        parts.append((inspect.cleandoc(command.help or "")).strip() + "\n")
        parts.append(f"```\n{' '.join(usage.split())}\n```\n")
        if arguments or options:
            parts.append("| Argument / option | Type | Default | Description |\n|---|---|---|---|")
            for param in [*arguments, *options]:
                parts.append(_param_row(param))
            parts.append("")

    walk(root, [])
    return "\n".join(parts)


def _arg_usage(argument: Any) -> str:
    name = argument.human_readable_name.upper()
    name = f"{name}..." if argument.multiple or argument.nargs == -1 else name
    return name if argument.required else f"[{name}]"


def _param_row(param: Any) -> str:
    if param.param_type_name == "option":
        flags = ", ".join(f"`{o}`" for o in [*param.opts, *param.secondary_opts])
        help_text = param.help or ""
    else:
        flags = f"`{param.human_readable_name.upper()}`"
        help_text = getattr(param, "help", None) or ""
    kind = "flag" if getattr(param, "is_flag", False) else param.type.name.lower()
    kind = {"str": "string", "int": "integer", "float": "number"}.get(kind, kind)
    if getattr(param, "multiple", False) or param.nargs == -1:
        kind += ", repeatable"
    default = param.default
    shown = "—" if default in (None, (), []) or callable(default) else f"`{default}`"
    if param.required:
        shown = "**required**"
    return f"| {flags} | {kind} | {shown} | {help_text.replace('|', '\\|')} |"


# ---------------------------------------------------------------- HTTP API


def http_api() -> str:
    from ragkit.core.config import ProjectConfig
    from ragkit.server import create_app

    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "ragkit.yaml").write_text("name: docs\n")
        spec = create_app(ProjectConfig.load(tmp)).openapi()
    schemas = spec.get("components", {}).get("schemas", {})
    parts = [
        HEADER,
        "# HTTP API reference\n",
        "Endpoints served by `ragkit serve`, generated from the FastAPI app. A running "
        "server also serves this as OpenAPI at `/openapi.json` and interactive docs at "
        "`/docs`.\n",
        "When `auth.mode` is not `none`, send `Authorization: Bearer <API key or JWT>` (or "
        "`X-API-Key: <key>`). Missing or invalid credentials return 401, a missing scope "
        "403, and an exceeded rate limit 429 with `Retry-After`.\n",
        "| Method | Path | Summary |\n|---|---|---|",
    ]
    endpoints = [
        (method.upper(), path, op)
        for path, methods in spec["paths"].items()
        for method, op in methods.items()
    ]
    for method, path, op in endpoints:
        parts.append(f"| `{method}` | `{path}` | {_summary(op)} |")
    parts.append("")
    used: list[str] = []
    for method, path, op in endpoints:
        parts.append(f"## `{method} {path}`\n")
        if description := op.get("description"):
            parts.append(inspect.cleandoc(description) + "\n")
        params = [p for p in op.get("parameters", []) if p["in"] in ("query", "path")]
        if params:
            parts.append("| Parameter | In | Type | Required |\n|---|---|---|---|")
            for p in params:
                kind = _schema_type(p.get("schema", {}))
                parts.append(f"| `{p['name']}` | {p['in']} | {kind} | {p.get('required', False)} |")
            parts.append("")
        body = op.get("requestBody", {}).get("content", {}).get("application/json", {})
        if body:
            optional = "" if op["requestBody"].get("required") else " (optional)"
            parts.append(f"**Request body{optional}:** {_schema_type(body['schema'])}\n")
            used += _refs(body["schema"])
        for status, response in op.get("responses", {}).items():
            if not status.startswith("2") or path.endswith("stream"):
                continue
            schema = response.get("content", {}).get("application/json", {}).get("schema", {})
            name = _schema_type(schema)
            parts.append(f"**Response {status}:** {name}\n")
            used += [n for n in _refs(schema)]
        if path.endswith("stream"):
            parts.append(
                '**Response:** `text/event-stream` with events `start`, `token` (`{"text"}`), '
                'then `approval_required` (`{"thread_id", "pending"}`) or `end`; '
                "failures after the stream starts arrive as `error`.\n"
            )
    parts.append("## Schemas\n")
    for name in _closure(used, schemas):
        schema = schemas[name]
        parts.append(f"### {name}\n")
        if schema.get("description"):
            parts.append(schema["description"] + "\n")
        required = set(schema.get("required", []))
        parts.append("| Field | Type | Required | Description |\n|---|---|---|---|")
        for field, prop in schema.get("properties", {}).items():
            desc = (prop.get("description") or "").replace("\n", " ")
            parts.append(f"| `{field}` | {_schema_type(prop)} | {field in required} | {desc} |")
        parts.append("")
    return "\n".join(parts)


def _summary(op: dict[str, Any]) -> str:
    description = (op.get("description") or "").strip().split("\n")[0]
    return description or op.get("summary", "")


def _ref_name(schema: dict[str, Any]) -> str:
    return schema["$ref"].rsplit("/", 1)[1]


def _refs(schema: Any) -> list[str]:
    if isinstance(schema, dict):
        found = [_ref_name(schema)] if "$ref" in schema else []
        return found + [r for v in schema.values() for r in _refs(v)]
    if isinstance(schema, list):
        return [r for v in schema for r in _refs(v)]
    return []


def _closure(names: list[str], schemas: dict[str, Any]) -> list[str]:
    ordered: list[str] = []
    pending = list(dict.fromkeys(names))
    while pending:
        name = pending.pop(0)
        if name in ordered or name not in schemas:
            continue
        ordered.append(name)
        pending += _refs(schemas[name])
    return ordered


def _schema_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        name = _ref_name(schema)
        return f"[`{name}`](#{name.lower()})"
    if "anyOf" in schema:
        options = [s for s in schema["anyOf"] if s.get("type") != "null"]
        nullable = len(options) < len(schema["anyOf"])
        return " \\| ".join(_schema_type(s) for s in options) + (" \\| null" if nullable else "")
    if schema.get("type") == "array":
        return f"list of {_schema_type(schema.get('items', {}))}"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "const" in schema:
        return f"`{schema['const']}`"
    if schema.get("type") == "object" and "additionalProperties" in schema:
        return "object"
    return schema.get("type", "any")


# ---------------------------------------------------------------- templates


def templates() -> str:
    from ragkit.agents import list_templates

    parts = [
        HEADER,
        "# Templates\n",
        "Built-in agent templates, copied into a project with "
        "`ragkit add agent <template>`. The copy is yours to edit.\n",
        "| Template | Pattern | Description |\n|---|---|---|",
    ]
    found = list_templates()
    for template in found:
        parts.append(
            f"| [`{template.name}`](#{template.name}) | `{template.pattern}` | "
            f"{template.description} |"
        )
    parts.append("")
    for template in found:
        files = sorted(
            p.relative_to(template.path).as_posix()
            for p in template.path.rglob("*")
            if p.is_file() and "__pycache__" not in p.parts and p.name != "README.md"
        )
        readme = (template.path / "README.md").read_text().split("\n", 1)[1].strip()
        readme = "\n".join(
            ("#" + line) if line.startswith("#") else line for line in readme.splitlines()
        )
        manifest = (template.path / "agent.yaml").read_text().strip()
        parts += [
            f"## `{template.name}` {{#{template.name}}}\n",
            readme + "\n",
            f"Files: {', '.join(f'`{f}`' for f in files)}\n",
            '??? example "agent.yaml"\n',
            "    ```yaml",
            *(f"    {line}" if line else "" for line in manifest.splitlines()),
            "    ```\n",
        ]
    return "\n".join(parts)


PAGES = {
    "project-config.md": project_config,
    "agent-manifest.md": agent_manifest,
    "cli.md": cli,
    "http-api.md": http_api,
    "templates.md": templates,
}


def generate() -> dict[str, str]:
    return {name: build().rstrip() + "\n" for name, build in PAGES.items()}


def main() -> int:
    pages = generate()
    if "--check" in sys.argv:
        stale = [
            n
            for n, text in pages.items()
            if not (REFERENCE / n).exists() or (REFERENCE / n).read_text() != text
        ]
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run: uv run python docs/gen_reference.py")
            return 1
        return 0
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (REFERENCE / name).write_text(text)
        print(f"wrote docs/reference/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
